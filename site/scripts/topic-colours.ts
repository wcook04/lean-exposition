#!/usr/bin/env node
// Compute every topic list's colours once and store them beside its phrases.
//
// A topic list is one part of a phrases file: its topics, in order, with their families. Lists that
// are the same (the pages of one Proof Reader paper share one) are seriated once, on relatedness
// pooled over every page that uses them, so they get the same colours on every page. For each
// alignment/phrases-<slot>.json this writes alignment/colours-<slot>.json, and it writes the
// orders and colours of every list to site/tests/fixtures/topic-colours.json, so a data change shows
// up as a diff to review. The Python reader and the site read the stored colours; nothing is
// computed while a page loads.
//
// Usage (from anywhere): node site/scripts/topic-colours.ts [--check] [--report]
//   --check   write nothing; exit 1 when a stored file differs from what the data gives
//   --report  print each list's floors
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { palette, relatedness, type FamilyIn, type Palette, type PhraseIn, type TopicIn } from "../src/reader/palette.ts";

export const ROOT = resolve(import.meta.dirname, "../..");
export const FIXTURE = resolve(ROOT, "site/tests/fixtures/topic-colours.json");
const SCHEMA = "topic-colours/1";
const MEANING =
  "Generated by site/scripts/topic-colours.ts from the topics, families and phrases of this paper and of every page that shares its topic list; do not edit. Each family has one hue and each topic one shade of it.";

/** Where an example's or instance's paper text is, by slot. */
function paperText(alignment: string, slot: string): string | null {
  const home = resolve(alignment, "..");
  const name = home.split("/").pop()!;
  const file = { long: "reasoning-record.md", short: "paper.md", expository: "main.md" }[slot] ?? "paper.md";
  for (const path of [resolve(ROOT, "papers", name, slot, file), resolve(home, "papers", slot, "paper.md"), resolve(home, "papers", slot, file)])
    if (existsSync(path)) return readFileSync(path, "utf8");
  return null;
}

/** The innermost heading before each offset, as the reader's sections are cut. */
function sectionAt(text: string): (offset: number) => string {
  const heads: [number, string][] = [];
  for (const m of text.matchAll(/^#{1,6} .*$/gm)) heads.push([m.index!, m[0]]);
  return (offset) => {
    let found = "";
    for (const [at, title] of heads) {
      if (at > offset) break;
      found = title;
    }
    return found;
  };
}

interface Row {
  id: string;
  topic: string;
  from: string;
  after?: string;
  lean?: { name: string; file?: string }[];
}

interface ListUse {
  file: string; // colours file to write, relative to ROOT
  part: number;
}

interface List {
  key: string;
  topics: TopicIn[];
  families?: FamilyIn[];
  related: number[][];
  uses: ListUse[];
}

export function keyOf(topics: TopicIn[], families?: FamilyIn[]): string {
  const used = new Set(topics.map((t) => t.family).filter(Boolean));
  const canon = JSON.stringify({
    topics: topics.map((t) => [t.id, t.family ?? null]),
    families: (families ?? []).filter((f) => used.has(f.id)).map((f) => [f.id, f.name]),
  });
  return createHash("sha256").update(canon).digest("hex").slice(0, 16);
}

/** Every phrases file under examples/ and instances/. */
function phraseFiles(): string[] {
  const out: string[] = [];
  for (const top of ["examples", "instances"]) {
    const dir = resolve(ROOT, top);
    if (!existsSync(dir)) continue;
    for (const name of readdirSync(dir).sort()) {
      const alignment = resolve(dir, name, "alignment");
      if (!existsSync(alignment)) continue;
      for (const f of readdirSync(alignment).sort()) if (/^phrases-.*\.json$/.test(f)) out.push(resolve(alignment, f));
    }
  }
  return out;
}

export interface Computed {
  files: Map<string, string>; // absolute path -> content
  fixture: string;
  palettes: { key: string; uses: string[]; topics: number; palette: Palette }[];
}

export function compute(): Computed {
  const lists = new Map<string, List>();
  const perFile: { path: string; slot: string; keys: string[] }[] = [];
  for (const path of phraseFiles()) {
    const data = JSON.parse(readFileSync(path, "utf8"));
    const slot = String(data.paper);
    const text = paperText(resolve(path, ".."), slot);
    const section = text ? sectionAt(text) : () => "";
    const families: FamilyIn[] | undefined = data.families;
    const colours = resolve(path, "..", `colours-${slot}.json`);
    const keys: string[] = [];
    (data.parts as { topics: TopicIn[] }[]).forEach((part, n) => {
      const topics = part.topics.map((t) => ({ id: t.id, name: t.name, ...(t.family ? { family: t.family } : {}) }));
      const ids = new Set(topics.map((t) => t.id));
      const phrases: PhraseIn[] = (data.ties as Row[])
        .filter((row) => ids.has(row.topic))
        .map((row) => {
          let begin = 0;
          if (text && row.after) {
            const a = text.indexOf(row.after);
            if (a >= 0) begin = a + row.after.length;
          }
          const at = text ? text.indexOf(row.from, begin) : -1;
          return { topic: row.topic, section: at >= 0 ? section(at) : "", lean: (row.lean ?? []).map((l) => `${l.file ?? ""}:${l.name}`) };
        });
      const key = keyOf(topics, families);
      const rel = relatedness(topics.map((t) => t.id), phrases);
      const list = lists.get(key);
      if (list) {
        list.related = list.related.map((row, i) => row.map((v, j) => v + rel[i][j]));
        list.uses.push({ file: relative(ROOT, colours), part: n });
      } else lists.set(key, { key, topics, families, related: rel, uses: [{ file: relative(ROOT, colours), part: n }] });
      keys.push(key);
    });
    perFile.push({ path: colours, slot, keys });
  }
  const palettes = new Map<string, Palette>();
  for (const [key, list] of [...lists].sort(([a], [b]) => a.localeCompare(b))) palettes.set(key, palette(list));
  const files = new Map<string, string>();
  for (const { path, slot, keys } of perFile) {
    const parts = keys.map((key) => {
      const p = palettes.get(key)!;
      return {
        key,
        shared_by: lists.get(key)!.uses.length,
        lightness: p.lightness,
        chroma: p.chroma,
        families: p.families,
        topics: Object.fromEntries(p.topics.map((t) => [t.id, { index: t.index, family: t.family, light: t.light, dark: t.dark }])),
      };
    });
    files.set(path, JSON.stringify({ schema: SCHEMA, paper: slot, meaning: MEANING, parts }, null, 1) + "\n");
  }
  const fixture: Record<string, unknown> = {};
  for (const [key, list] of [...lists].sort(([a], [b]) => a.localeCompare(b))) {
    const p = palettes.get(key)!;
    fixture[key] = {
      used_by: list.uses.map((u) => `${u.file}#${u.part}`),
      families: p.families.map((f) => [f.id, f.hue, f.topics]),
      colours: Object.fromEntries(p.topics.map((t) => [t.id, [t.light, t.dark]])),
    };
  }
  return {
    files,
    fixture: JSON.stringify(fixture, null, 1) + "\n",
    palettes: [...lists.values()].map((l) => ({ key: l.key, uses: l.uses.map((u) => `${u.file}#${u.part}`), topics: l.topics.length, palette: palettes.get(l.key)! })),
  };
}

export function report(c: Computed): string {
  const lines: string[] = [];
  for (const { key, uses, topics, palette: p } of c.palettes) {
    lines.push(`${uses[0]}${uses.length > 1 ? ` (+${uses.length - 1} sharing)` : ""} [${key}] ${topics} topics in ${p.families.length} families ${p.families.map((f) => f.topics.length).join("+")}; L ${p.lightness.light}/${p.lightness.dark}, C ${p.chroma.light.join('–')}/${p.chroma.dark.join('–')}`);
    for (const r of p.floors) lines.push(`  ${r.theme.padEnd(5)} ${r.vision.padEnd(12)} families ΔE ≥ ${r.family.toFixed(1).padStart(5)}   shades ΔE ≥ ${Number.isFinite(r.shade) ? r.shade.toFixed(1).padStart(5) : "    —"}   contrast ≥ ${r.contrast.toFixed(2)}`);
  }
  return lines.join("\n");
}

// Run as a script: compared as URLs, so a path with a space (percent-encoded in the URL) still matches.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  const c = compute();
  let stale = 0;
  const all: [string, string][] = [...c.files, [FIXTURE, c.fixture]];
  for (const [path, content] of all) {
    const old = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (old === content) continue;
    stale++;
    if (check) console.error(`stale: ${relative(ROOT, path)}`);
    else writeFileSync(path, content);
  }
  if (process.argv.includes("--report")) console.log(report(c));
  if (check && stale) process.exit(1);
  console.log(check ? "topic colours are current" : `topic colours: ${c.files.size} files, ${c.palettes.length} lists, ${stale} written`);
}
