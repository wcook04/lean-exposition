#!/usr/bin/env python3
"""Write the Proof Reader redirect table: every Proof Reader page now read in the library, and how
each of its old hash addresses maps to its library address (docs/library-architecture.md, section 6).

    proof_reader_redirects.py PROOF_READER_CHECKOUT OUT.json [--js OUT.js] [--instance ID]
      [--ns-table REDIRECTS.json] [--verified-bookmarks BOOKMARKS.json] [--base-table TABLE.json] [--offline]

Pages come from the library instances (instances/*/instance.json: the main document's Proof Reader
page, and each companion document read from a single page) and, for Navier–Stokes, from the table of
its companion pages (--ns-table). A page is written only when its library address answers 200 now,
so a page whose library copy is not yet live stays on Proof Reader (--offline skips that check).

For each page the table holds:
  to        its library address
  root      its paper's library address (the Lean index lives there)
  claims    old claim id -> the address after `to` (a numbered result "theorem-1.1/", or the
            claim's passage "@<id>" on a companion page)
  retired   true for a removed companion whose old addresses open the original paper
  headings  old heading id (and each alias) -> the library's section anchor ("" for an unnumbered
            heading, which opens the page at its top); read from the live Proof Reader edition
  bookmarks only these verified old record spellings move; the original reader keeps every other address
The JS file holds the table and the mapping the stub runs before Proof Reader's own code.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIB = "https://wcook04.github.io/library/"
PR = "https://wcook04.github.io/proof-reader/"


def fetch_json(url: str):
    try:
        with urllib.request.urlopen(url, timeout=30) as r:
            return json.load(r)
    except Exception:
        return None


def live(url: str) -> bool:
    try:
        with urllib.request.urlopen(url, timeout=30) as r:
            return r.status == 200
    except Exception:
        return False


def anchor(number: str) -> str:
    """Proof Reader's heading number as the library's section anchor ("4.2", "appendix-a")."""
    if not number:
        return ""
    m = re.match(r"^(?:Appendix\s+)?([A-Z])(?:\.(\d+(?:\.\d+)*))?$", number)
    if m:
        return "appendix-" + m.group(1).lower() + (f".{m.group(2)}" if m.group(2) else "")
    return number.rstrip(".")


def headings(slug: str) -> dict[str, str]:
    edition = fetch_json(f"{PR}papers/{slug}/edition.json") or {}
    reading = edition.get("reading") or {}
    out = {row["id"]: anchor(str(row.get("number") or "")) for row in reading.get("outline") or []}
    for old, new in (reading.get("heading_aliases") or {}).items():
        if new in out:
            out.setdefault(old, out[new])
    return out


JS = r"""// Proof Reader pages now read in the library: each old hash address goes to its library address
// (generated by lean-exposition scripts/proof_reader_redirects.py; do not edit by hand). Runs before
// the app, so a moved page never draws. An address the table does not know stays on Proof Reader.
(function () {
  var T = __TABLE__;
  var nativePaper = null;
  function dec(s) { try { return decodeURIComponent(s); } catch (e) { return s; } }
  function target(hash) {
    var m = /^#\/?([^\/#]+)(?:#([^#]+)|\/([^\/]*)(?:\/.*)?)?$/.exec(hash);
    if (!m) return null;
    var slug = dec(m[1]);
    if (!Object.prototype.hasOwnProperty.call(T, slug)) return null;
    var e = T[slug];
    if (e.retired) return e.to;
    var rec = m[2] !== undefined ? "@" + dec(m[2]) : m[3] ? dec(m[3]) : "";
    if (e.bookmarks) {
      // A visit to a retained view uses the original reader for the rest of that paper's visit.
      if (nativePaper === slug) return null;
      if (/^#\/?[^\/#]+\/[^/]*\//.test(hash)) return null;
      if (!rec) return e.to;
      return Object.prototype.hasOwnProperty.call(e.bookmarks, rec) ? e.to + e.bookmarks[rec] : null;
    }
    if (!rec) return e.to;
    if (rec.charAt(0) === "@") {
      var k = rec.slice(1);
      if (/^page-\d+$/.test(k)) return e.to + "?view=pdf&page=" + k.slice(5);
      if (k === "declarations") return e.root + "lean?list=papers";
      if (k === "file") return e.root + "lean";
      if (k === "sheet" || k === "") return e.to;
      if (Object.prototype.hasOwnProperty.call(e.headings, k)) return e.to + (e.headings[k] ? "#" + e.headings[k] : "");
      if (Object.prototype.hasOwnProperty.call(e.claims, k)) return e.to + e.claims[k];
      return e.to + "@" + encodeURIComponent(k);
    }
    if (Object.prototype.hasOwnProperty.call(e.claims, rec)) return e.to + e.claims[rec];
    // Anything else after the page is a Lean declaration's name; the library opens its card, or says it is not there.
    return e.to + "lean/" + encodeURIComponent(rec).replace(/%2E/g, ".");
  }
  window.__libraryTarget = target;
  function forward() {
    // A static /proof-reader/<slug>/ address may still carry an old heading fragment.
    var hash = location.hash;
    var nativeHash = null;
    if (!/^#\//.test(hash)) {
      var page = /\/proof-reader\/([^\/]+)\/?$/.exec(location.pathname);
      if (page) {
        hash = "#/" + page[1] + hash;
        if (Object.prototype.hasOwnProperty.call(T, page[1]) && T[page[1]].bookmarks) nativeHash = hash;
      }
    }
    var to = target(hash);
    if (to) {
      document.documentElement.style.visibility = "hidden";
      location.replace(to);
    } else {
      var slug = dec((/^#\/?([^\/#]+)/.exec(hash) || ["", ""])[1]);
      nativePaper = Object.prototype.hasOwnProperty.call(T, slug) && T[slug].bookmarks ? slug : null;
      if (nativeHash && location.hash) location.replace(location.pathname.replace(/[^/]+\/?$/, "") + nativeHash);
    }
  }
  window.addEventListener("hashchange", forward);
  forward();
})();
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("proof_reader", type=Path, help="a checkout of wcook04/proof-reader (its papers/*/links.json)")
    ap.add_argument("out", type=Path)
    ap.add_argument("--js", type=Path)
    ap.add_argument("--instance", action="append", help="only include the selected library instance; repeat to select several")
    ap.add_argument("--ns-table", type=Path, help="the Navier–Stokes companion pages' table (paper, pages)")
    ap.add_argument("--verified-bookmarks", type=Path, help="only move these old pages and verified records; JSON keyed by old page then record")
    ap.add_argument("--base-table", type=Path, help="preserve other entries in this existing table")
    ap.add_argument("--offline", action="store_true", help="write every page without checking that its library address is live")
    args = ap.parse_args()
    papers = args.proof_reader / "papers"
    pages: dict[str, dict] = {}

    def claim_passages(slug: str) -> dict[str, str]:
        links = papers / slug / "links.json"
        if not links.is_file():
            return {}
        return {c["id"]: f"@{c['passage']}" for c in json.loads(links.read_text()).get("claims", []) if c.get("passage")}

    for path in sorted((ROOT / "instances").glob("*/instance.json")):
        inst = json.loads(path.read_text())
        source = (inst.get("source") or {}).get("proof_reader") or {}
        if args.instance and inst["id"] not in args.instance:
            continue
        at = inst.get("path") or inst["id"]
        root = f"{LIB}{at}/"  # the build's own Lean index
        if source.get("page"):
            aliases = path.parent / "alignment/aliases.json"
            claims = json.loads(aliases.read_text()).get("claims", {}) if aliases.is_file() else {}
            pages[source["page"]] = {"to": f"{LIB}{at}/", "root": root, "claims": {k: f"{v}/" for k, v in claims.items()}}
        for doc in inst["documents"]:
            if doc.get("main") or not doc.get("slot") or not doc.get("slug") or "+" in doc["id"]:
                continue
            if (papers / doc["id"] / "links.json").is_file():
                pages[doc["id"]] = {"to": f"{LIB}{at}/{doc['slug']}/", "root": root, "claims": claim_passages(doc["id"])}
        for removed in inst.get("removed_pages", []):
            slug = f"{inst['id']}-{removed}"
            if inst["id"] == "navier-stokes" and removed == "what-the-lean-states":
                slug = inst["id"]
            if (papers / slug / "paper.toml").is_file():
                pages[slug] = {"to": root, "root": root, "claims": {}, "retired": True}
    if args.ns_table and args.ns_table.is_file() and (not args.instance or "navier-stokes" in args.instance):
        table = json.loads(args.ns_table.read_text())
        ns = json.loads((ROOT / "instances/navier-stokes/instance.json").read_text())
        removed = set(ns.get("removed_pages", []))
        for slug, row in (table.get("pages") or {}).items():
            # A companion the library no longer publishes sends its old Proof Reader address to the paper.
            if row["page"] in removed:
                pages[slug] = {"to": f"{LIB}navier-stokes/", "root": f"{LIB}navier-stokes/", "claims": {}, "retired": True}
            else:
                pages[slug] = {"to": f"{LIB}navier-stokes/{row['page']}/", "root": f"{LIB}navier-stokes/", "claims": claim_passages(slug)}
    if args.verified_bookmarks:
        verified = json.loads(args.verified_bookmarks.read_text())
        unknown = verified.keys() - pages.keys()
        if unknown:
            ap.error(f"no Library page for {', '.join(sorted(unknown))}")
        pages = {
            slug: {**pages[slug], "bookmarks": bookmarks}
            for slug, bookmarks in verified.items()
        }
        for slug, row in pages.items():
            for old, target in row["bookmarks"].items():
                if not old or not isinstance(target, str) or not target.startswith(("?", "#", "@", "lean/")):
                    ap.error(f"invalid verified bookmark for {slug}: {old!r} → {target!r}")
    base = json.loads(args.base_table.read_text()) if args.base_table else {}
    out = dict(base.get("pages", {}))
    held = set(base.get("held", []))
    live_by_url: dict[str, bool] = {}
    for slug in sorted(pages):
        row = pages[slug]
        if not args.offline:
            url = row["to"]
            if url not in live_by_url:
                live_by_url[url] = live(url)
            if not live_by_url[url]:
                held.add(slug)
                continue
        held.discard(slug)
        older = out.get(slug)
        if older and "bookmarks" in older and "bookmarks" not in row:
            if (older["to"], older["root"]) != (row["to"], row["root"]):
                ap.error(f"recheck verified bookmarks for moved Library page {slug}")
            row["bookmarks"] = older["bookmarks"]
        row["headings"] = {} if row.get("retired") or "bookmarks" in row else headings(slug)
        out[slug] = row
    out = dict(sorted(out.items()))
    held = sorted(held)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps({"schema": 1, "from": PR, "pages": out, "held": held}, indent=1, ensure_ascii=False) + "\n")
    if args.js:
        args.js.write_text(JS.replace("__TABLE__", json.dumps(out, ensure_ascii=False, separators=(",", ":"))))
    print(f"proof-reader redirects: {len(out)} page(s) live in the library; held on Proof Reader: {', '.join(held) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
